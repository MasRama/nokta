// Writes src/generated/contracts.ts: one introspection XML string per
// interface in ../contracts, for Gio.DBusProxy.makeProxyWrapper().
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const contractsDir = new URL('../../contracts/', import.meta.url);
const outFile = new URL('../src/generated/contracts.ts', import.meta.url);

const files = readdirSync(contractsDir).filter((f) => /^io\.nokta\.\w+\.xml$/.test(f)).sort();
if (files.length === 0) {
    console.error(`gen-contracts: no contracts found in ${contractsDir.pathname}`);
    process.exit(1);
}

let out = '// Generated by scripts/gen-contracts.mjs from contracts/*.xml. Do not edit.\n';
for (const file of files) {
    const text = readFileSync(new URL(file, contractsDir), 'utf8');
    const start = text.indexOf('<node');
    const end = text.lastIndexOf('</node>');
    if (start < 0 || end < 0) {
        console.error(`gen-contracts: ${file} has no <node> element`);
        process.exit(1);
    }
    const xml = text
        .slice(start, end + '</node>'.length)
        .replace(/<!--[\s\S]*?-->/g, '')
        .split('\n')
        .map((line) => line.trimEnd())
        .filter((line) => line.trim() !== '')
        .join('\n');
    if (xml.includes('`') || xml.includes('${')) {
        console.error(`gen-contracts: ${file} contains characters that cannot go in a template literal`);
        process.exit(1);
    }
    const constant = `${file.replace(/^io\.nokta\./, '').replace(/\.xml$/, '').toUpperCase()}_XML`;
    out += `\nexport const ${constant} = \`${xml}\`;\n`;
}

mkdirSync(new URL('.', outFile), { recursive: true });
writeFileSync(outFile, out);
